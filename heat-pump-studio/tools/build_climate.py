# Heat Pump Studio — temperature bins for the seasonal calculation, from 10 years of hourly reanalysis data.
# Run from the repo root:   python heat-pump-studio/tools/build_climate.py
# Source: Open-Meteo historical weather API (https://open-meteo.com), ERA5-based, licence CC BY 4.0.
# Writes data/climate.js: per city, the average number of hours per year in each 1 K bin of outdoor temperature
# (bin j holds j−0.5 ≤ T < j+0.5), the annual mean, and the temperature exceeded in all but 0.4 % of hours (a statistical
# cross-check on the design outdoor temperature).
import json, os, time, urllib.request, math

HERE = os.path.dirname(os.path.abspath(__file__)); APP = os.path.abspath(os.path.join(HERE, ".."))
CITIES = [("Copenhagen", 55.68, 12.57), ("Aarhus", 56.16, 10.21), ("Oslo", 59.91, 10.75), ("Helsinki", 60.17, 24.94),
          ("Berlin", 52.52, 13.40), ("Munich", 48.14, 11.58), ("Vienna", 48.21, 16.37), ("Warsaw", 52.23, 21.01),
          ("Paris", 48.86, 2.35), ("London", 51.51, -0.13), ("Milan", 45.46, 9.19), ("Madrid", 40.42, -3.70),
          ("Barcelona", 41.39, 2.17), ("Santiago de Chile", -33.45, -70.67), ("Buenos Aires", -34.60, -58.38),
          ("Mexico City", 19.43, -99.13), ("Bogotá", 4.71, -74.07)]
START, END, YEARS = "2015-01-01", "2024-12-31", 10

out = {"source": "Open-Meteo historical weather API (ERA5), CC BY 4.0", "period": "%s to %s" % (START, END), "cities": {}}
for name, lat, lon in CITIES:
    url = ("https://archive-api.open-meteo.com/v1/archive?latitude=%.2f&longitude=%.2f&start_date=%s&end_date=%s"
           "&hourly=temperature_2m&timezone=GMT" % (lat, lon, START, END))
    for attempt in range(4):
        try:
            with urllib.request.urlopen(url, timeout=120) as r: d = json.load(r); break
        except Exception as e:
            print("  retry", name, e); time.sleep(5 * (attempt + 1))
    temps = [t for t in d["hourly"]["temperature_2m"] if t is not None]
    bins = {}
    for t in temps: j = int(math.floor(t + 0.5)); bins[j] = bins.get(j, 0) + 1
    lo, hi = min(bins), max(bins)
    hours = [round(bins.get(j, 0) / YEARS, 2) for j in range(lo, hi + 1)]
    s = sorted(temps)
    out["cities"][name] = {"lat": lat, "lon": lon, "elevation": d.get("elevation"), "tMin": lo, "hours": hours,
                           "mean": round(sum(temps) / len(temps), 2), "p004": round(s[int(0.004 * len(s))], 1), "n": len(temps)}
    print("%-18s %6d h  mean %5.1f °C  0.4 %% %5.1f °C  bins %d..%d" % (name, len(temps), out["cities"][name]["mean"], out["cities"][name]["p004"], lo, hi))
    time.sleep(1.5)

with open(os.path.join(APP, "data", "climate.js"), "w", encoding="utf-8") as f:
    f.write("// Heat Pump Studio — outdoor temperature bins (hours per year per 1 K), generated by tools/build_climate.py from the\n"
            "// Open-Meteo historical weather API (ERA5 reanalysis, %s), licence CC BY 4.0. Do not edit.\n" % out["period"])
    f.write("(function (root) { root.HPS_CLIMATE = ")
    json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
    f.write("; if (typeof module !== \"undefined\" && module.exports) module.exports = root.HPS_CLIMATE; })(typeof self !== \"undefined\" ? self : this);\n")
print("data/climate.js %.0f kB" % (os.path.getsize(os.path.join(APP, "data", "climate.js")) / 1024))

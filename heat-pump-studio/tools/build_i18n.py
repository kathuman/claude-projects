# Heat Pump Studio — writes i18n-es.js and i18n-da.js from tools/translations.py.
# Run from the repo root:   python heat-pump-studio/tools/build_i18n.py
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); APP = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
from translations import T, H
import translations_season as _s
T.update(_s.T); H.update(_s.H)
import translations_v12 as _v
T.update(_v.T); H.update(_v.H)
import translations_learn as _l
T.update(_l.T); H.update(_l.H)

def js(var, label, idx):
    t = {k: v[idx] for k, v in T.items()}; h = {k: v[idx] for k, v in H.items()}
    return ("// Heat Pump Studio — %s. Generated by tools/build_i18n.py from tools/translations.py; edit those, not this.\n"
            "(function (root) {\n  \"use strict\";\n  root.%s = {\n    T: %s,\n    H: %s\n  };\n})(typeof self !== \"undefined\" ? self : this);\n"
            % (label, var, json.dumps(t, ensure_ascii=False, indent=6)[:-1] + "    }", json.dumps(h, ensure_ascii=False, indent=6)[:-1] + "    }"))
open(os.path.join(APP, "i18n-es.js"), "w", encoding="utf-8").write(js("HPS_ES", "español (América Latina)", 0))
open(os.path.join(APP, "i18n-da.js"), "w", encoding="utf-8").write(js("HPS_DA", "dansk", 1))
print("written: %d messages, %d page texts" % (len(T), len(H)))

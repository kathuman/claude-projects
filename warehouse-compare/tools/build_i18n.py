# Builds i18n-es.js and i18n-da.js from tools/translations.py.
#   python warehouse-compare/tools/build_i18n.py
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import translations as tr

seen = set()
for en, es, da in tr.T:
    assert en not in seen, "duplicate message: " + en
    seen.add(en)

def build(lang, idx, name, title):
    T = {en: (es if idx == 0 else da) for en, es, da in tr.T}
    H = {k: v[idx] for k, v in tr.H.items()}
    P = {k: list(v[idx]) for k, v in tr.P.items()}
    C = {k: v[idx] for k, v in tr.C.items()}
    FIELDS = ["name", "mechanism", "strengths", "weaknesses", "best_fit"]
    A = {k: dict(zip(FIELDS, v[idx])) for k, v in tr.A.items()}
    body = json.dumps({"T": T, "H": H, "P": P, "C": C, "A": A}, ensure_ascii=False, indent=2)
    out = ("// Warehouse Compare — " + title + ". Generated by tools/build_i18n.py from tools/translations.py; edit those, not this.\n"
           "(function (root) {\n  \"use strict\";\n  root." + name + " = " + body.replace("\n", "\n  ") + ";\n})(typeof self !== \"undefined\" ? self : this);\n")
    open(os.path.join(here, "..", "i18n-" + lang + ".js"), "w", encoding="utf-8", newline="\n").write(out)
    print(lang, len(T), "messages,", len(H), "page keys,", len(P), "inputs,", len(C), "choices,", len(A), "technologies")

build("es", 0, "WC_ES", "español (Latinoamérica)")
build("da", 1, "WC_DA", "dansk")

// Builds src/openings-data.js from lichess-org/chess-openings (CC0): node chess/tests/build-openings.js <dir with a.tsv … e.tsv>
// Every line is replayed through the rules, so an illegal or mistyped line fails the build.
const R = require("../src/rules.js"), fs = require("fs");
const out = [];
let t0 = Date.now(), plies = 0;
for (const f of "abcde") {
  const rows = fs.readFileSync(require("path").join(process.argv[2], f) + ".tsv", "utf8").trim().split("\n").slice(1);
  for (const row of rows) {
    const [eco, name, pgn] = row.split("\t");
    const g = R.parsePGN(pgn);
    if (g.error) throw new Error(row + " " + g.error);
    const ucis = g.moves.map((m) => R.toUCI(m));
    plies += ucis.length;
    out.push(eco + "\t" + name + "\t" + ucis.join(" "));
  }
}
console.log(out.length, "lines", plies, "plies", Date.now() - t0, "ms");
const js = "/* Opening names: lichess-org/chess-openings (CC0 1.0), https://github.com/lichess-org/chess-openings\n" +
  " * Generated by tests/build-openings.js — one line per named opening: ECO, name, moves in UCI. */\n" +
  "(typeof self !== \"undefined\" ? self : this).CHESS_OPENINGS_DATA = " + JSON.stringify(out.join("\n")) + ";\n";
fs.writeFileSync(require("path").join(__dirname, "../src/openings-data.js"), js);
console.log("bytes", js.length);
